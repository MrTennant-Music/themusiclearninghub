'use strict';
// Reuse reviewed Hub recordings; never regenerate or edit the source questions.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const m4aDuration = require('./lib/m4a-duration.cjs');
const root = path.resolve(__dirname, '..');
const dictionary = require(path.join(root, 'shared/music-games-concepts.js'));
const fullDictionary = require(path.join(root, 'music-dictionary/music-concepts-data.js'));
const vm = require('node:vm');
const context = {window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'music-dictionary/quiz-bank.js'), 'utf8'), context);
const bank = context.window.MUSIC_DICTIONARY_QUIZ_BANK;
const quiz = require(path.join(root, 'music-dictionary/quiz-core.js'));
const levels = ['N3', 'N4', 'N5', 'H', 'AH'];
const concepts = fullDictionary.concepts.map(({id,name,definition,level}) => ({id,name,definition,level:levels[fullDictionary.levels.indexOf(level)]}));
const questions = bank.questions.filter(q => q.format === 'multiple-choice' && quiz.eligibleForQuiz(q,{level:q.levelCode}) && !quiz.validateQuestion(q).length && !(bank.retiredConceptIds || []).includes(q.conceptId));
const knowledge = questions.filter(q => q.modality === 'text').map(q => ({questionId:q.id,level:q.levelCode,conceptId:q.conceptId,prompt:q.prompt,options:q.options.map(({id,text})=>({id,text})),correctOptionIds:q.answer.correctOptionIds,feedback:q.feedback}));
const audio = questions.filter(q => q.modality === 'audio').map(q => {
  const media = q.media, file = path.resolve(root, decodeURIComponent(media.src));
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file)) throw Error('Missing local recording: ' + media.src);
  const bytes = fs.readFileSync(file);
  const duration = path.extname(file).toLowerCase() === '.m4a' ? m4aDuration(bytes) : media.duration;
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  if (media.sha256 && sha256 !== media.sha256) throw Error('Recording changed: ' + q.id);
  const start = media.startSeconds ?? media.start ?? 0;
  const end = Math.min(media.endSeconds ?? media.end ?? media.duration, duration);
  if (!(Number.isFinite(start) && Number.isFinite(end) && start >= 0 && end > start && end <= media.duration)) throw Error('Invalid recording window: ' + q.id);
  return {conceptId:q.conceptId,src:media.src,start,end,credit:media.recording,level:q.levelCode,questionId:q.id,prompt:q.prompt,options:q.options.map(({id,text})=>({id,text})),correctOptionIds:q.answer.correctOptionIds,feedback:q.feedback,sha256,finalisedAt:q.review?.finalisedAt};
});
for (const level of levels) if (knowledge.filter(q=>q.level===level).length < 6 || audio.filter(q=>q.level===level).length < 6) throw Error('Insufficient questions for '+level);
const content = {version:2,levels,concepts,knowledge,audio};
const output = '/* Generated by scripts/build-music-escape-content.cjs. */\n(function(root,data){if(typeof module==="object"&&module.exports)module.exports=data;else root.EscapeContent=data;})(typeof globalThis!=="undefined"?globalThis:this,' + JSON.stringify(content) + ');\n';
fs.mkdirSync(path.join(root, 'music-escape'), {recursive: true});
fs.writeFileSync(path.join(root, 'music-escape/content.js'), output);
console.log(`Music Escape: ${knowledge.length} bank multiple-choice questions, ${audio.length} bank listening questions.`);
