/* Explicit instrument practice destinations; notation activities are excluded. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const assignments={
 'example-piano-keys':['MC-0057'],
 'hub-s1-parts-of-the-guitar':['MC-0043'],
 'hub-s1-guitar-strings-and-frets':['MC-0043','MC-0050'],
 'hub-s1-parts-of-the-bass-guitar':['MC-0117'],
 'hub-s1-bass-guitar-strings-and-frets':['MC-0117'],
 'hub-s1-parts-of-the-drumkit':['MC-0049','MC-0056']
};
function build(){
 const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex').slice(0,12);
 const games=Object.entries(assignments).map(([id,conceptIds])=>{
  const a=JSON.parse(fs.readFileSync(path.join(root,'music-games/activities',id+'.json')));
  if(a.template!=='labelled-diagram'||a.tags?.includes('Music Literacy'))throw Error('Only instrument Label games belong in Dictionary Practice: '+id);
  return {id,title:a.title,conceptIds,level:a.level};
 });
 const files=Object.fromEntries(['music-games/runtime/index.js','music-games/core.js','music-games/loader.js','music-games/diagram-core.js','music-games/runtime/diagram.js','music-games/diagram.css'].map(file=>[file,'./'+file+'?v='+hash(file)]));
 const data={games,files};
 fs.writeFileSync(path.join(root,'music-dictionary/label-games-data.js'),'/* Generated by scripts/build-dictionary-label-games.cjs. */\n(function(r,d){if(typeof module===\'object\'&&module.exports)module.exports=d;else r.MusicDictionaryLabelData=d;})(typeof window===\'undefined\'?globalThis:window,'+JSON.stringify(data)+');\n');
 for(const page of ['conceptsort.html','conceptgames.html','crosswords.html','wordsearch.html','connections.html','conceptquiz.html','music-dictionary/musicdictionary.html','music-dictionary/musicdictionaryconcept.html']){
  const file=path.join(root,page);if(!fs.existsSync(file))continue;
  const html=fs.readFileSync(file,'utf8').replace(/(music-dictionary\/label-games-data\.js\?v=)[^"\s]+/g,'$1'+hash('music-dictionary/label-games-data.js'));
  fs.writeFileSync(file,html);
 }
 return data;
}
if(require.main===module)build();module.exports={assignments,build};
